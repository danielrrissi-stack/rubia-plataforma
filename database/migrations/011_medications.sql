CREATE TABLE prescriptions (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    patient_id INT UNSIGNED NOT NULL,
    drug_name VARCHAR(120) NOT NULL,
    route ENUM('oral','sublingual','subcutanea','intramuscular','topica','inalatoria','nasal','oftalmica','otologica','retal','vaginal','outra') NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NULL,
    end_reason VARCHAR(200) NULL,
    next_review_date DATE NULL,
    family_logs TINYINT(1) NOT NULL DEFAULT 0,
    secret TINYINT(1) NOT NULL DEFAULT 0,
    notes TEXT NULL,
    created_by INT UNSIGNED NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by INT UNSIGNED NULL,
    updated_at DATETIME NULL,
    deleted_at DATETIME NULL,
    deleted_by INT UNSIGNED NULL,
    KEY idx_prescriptions_patient (patient_id),
    CONSTRAINT fk_prescriptions_patient FOREIGN KEY (patient_id) REFERENCES patients(id),
    CONSTRAINT fk_prescriptions_creator FOREIGN KEY (created_by) REFERENCES users(id),
    CONSTRAINT fk_prescriptions_updater FOREIGN KEY (updated_by) REFERENCES users(id),
    CONSTRAINT fk_prescriptions_deleter FOREIGN KEY (deleted_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE prescription_doses (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    prescription_id INT UNSIGNED NOT NULL,
    effective_date DATE NOT NULL,
    dose VARCHAR(60) NOT NULL,
    frequency VARCHAR(120) NOT NULL,
    instructions TEXT NULL,
    reason VARCHAR(200) NULL,
    created_by INT UNSIGNED NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    KEY idx_prescription_doses_rx (prescription_id, effective_date),
    CONSTRAINT fk_prescription_doses_rx FOREIGN KEY (prescription_id) REFERENCES prescriptions(id),
    CONSTRAINT fk_prescription_doses_creator FOREIGN KEY (created_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE medication_logs (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    prescription_id INT UNSIGNED NOT NULL,
    given_at DATETIME NOT NULL,
    dose VARCHAR(60) NOT NULL,
    note VARCHAR(200) NULL,
    recorded_by INT UNSIGNED NOT NULL,
    recorded_by_role VARCHAR(20) NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at DATETIME NULL,
    deleted_by INT UNSIGNED NULL,
    KEY idx_medication_logs_rx (prescription_id, given_at),
    CONSTRAINT fk_medication_logs_rx FOREIGN KEY (prescription_id) REFERENCES prescriptions(id),
    CONSTRAINT fk_medication_logs_user FOREIGN KEY (recorded_by) REFERENCES users(id),
    CONSTRAINT fk_medication_logs_deleter FOREIGN KEY (deleted_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE adverse_events (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    patient_id INT UNSIGNED NOT NULL,
    prescription_id INT UNSIGNED NULL,
    occurred_on DATE NOT NULL,
    description TEXT NOT NULL,
    source ENUM('equipe','familia') NOT NULL,
    severity ENUM('leve','moderada','grave') NULL,
    conduct TEXT NULL,
    reported_by INT UNSIGNED NOT NULL,
    reported_by_role VARCHAR(20) NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_by INT UNSIGNED NULL,
    reviewed_at DATETIME NULL,
    deleted_at DATETIME NULL,
    deleted_by INT UNSIGNED NULL,
    KEY idx_adverse_events_patient (patient_id, occurred_on),
    CONSTRAINT fk_adverse_events_patient FOREIGN KEY (patient_id) REFERENCES patients(id),
    CONSTRAINT fk_adverse_events_rx FOREIGN KEY (prescription_id) REFERENCES prescriptions(id),
    CONSTRAINT fk_adverse_events_reporter FOREIGN KEY (reported_by) REFERENCES users(id),
    CONSTRAINT fk_adverse_events_reviewer FOREIGN KEY (reviewed_by) REFERENCES users(id),
    CONSTRAINT fk_adverse_events_deleter FOREIGN KEY (deleted_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
