CREATE TABLE measurements (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    patient_id INT UNSIGNED NOT NULL,
    measured_on DATE NOT NULL,
    weight_kg DECIMAL(6,3) NULL,
    height_cm DECIMAL(5,1) NULL,
    position ENUM('deitado','em_pe') NULL,
    waist_cm DECIMAL(5,1) NULL,
    hip_cm DECIMAL(5,1) NULL,
    head_cm DECIMAL(4,1) NULL,
    systolic SMALLINT NULL,
    diastolic SMALLINT NULL,
    source ENUM('equipe','familia') NOT NULL,
    retroactive TINYINT NOT NULL DEFAULT 0,
    previous_id INT UNSIGNED NULL,
    superseded_at DATETIME NULL,
    deleted_at DATETIME NULL,
    deleted_reason VARCHAR(255) NULL,
    created_by INT UNSIGNED NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    KEY idx_measurements_patient (patient_id, measured_on),
    CONSTRAINT fk_measurements_patient FOREIGN KEY (patient_id) REFERENCES patients(id),
    CONSTRAINT fk_measurements_prev FOREIGN KEY (previous_id) REFERENCES measurements(id),
    CONSTRAINT fk_measurements_creator FOREIGN KEY (created_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
