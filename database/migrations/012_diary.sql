CREATE TABLE diary_requests (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    patient_id INT UNSIGNED NOT NULL,
    type ENUM('alimentacao','agua','sono','atividade','tela','medidas') NOT NULL,
    weekdays TINYINT UNSIGNED NOT NULL DEFAULT 127,
    start_date DATE NOT NULL,
    end_date DATE NULL,
    guidance VARCHAR(255) NULL,
    secret TINYINT(1) NOT NULL DEFAULT 0,
    created_by INT UNSIGNED NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by INT UNSIGNED NULL,
    updated_at DATETIME NULL,
    deleted_at DATETIME NULL,
    deleted_by INT UNSIGNED NULL,
    KEY idx_diary_requests_patient (patient_id),
    CONSTRAINT fk_diary_requests_patient FOREIGN KEY (patient_id) REFERENCES patients(id),
    CONSTRAINT fk_diary_requests_creator FOREIGN KEY (created_by) REFERENCES users(id),
    CONSTRAINT fk_diary_requests_updater FOREIGN KEY (updated_by) REFERENCES users(id),
    CONSTRAINT fk_diary_requests_deleter FOREIGN KEY (deleted_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE diary_entries (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    request_id INT UNSIGNED NOT NULL,
    day DATE NOT NULL,
    meal ENUM('cafe_manha','lanche_manha','almoco','lanche_tarde','jantar','ceia','outro') NULL,
    meal_time TIME NULL,
    description VARCHAR(1000) NULL,
    glasses TINYINT UNSIGNED NULL,
    slept_at TIME NULL,
    woke_at TIME NULL,
    sleep_quality TINYINT UNSIGNED NULL,
    activity VARCHAR(120) NULL,
    minutes SMALLINT UNSIGNED NULL,
    photo_path VARCHAR(255) NULL,
    photo_mime VARCHAR(30) NULL,
    photo_size INT UNSIGNED NULL,
    recorded_by INT UNSIGNED NOT NULL,
    recorded_by_role VARCHAR(20) NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by INT UNSIGNED NULL,
    updated_at DATETIME NULL,
    deleted_at DATETIME NULL,
    deleted_by INT UNSIGNED NULL,
    KEY idx_diary_entries_request_day (request_id, day),
    CONSTRAINT fk_diary_entries_request FOREIGN KEY (request_id) REFERENCES diary_requests(id),
    CONSTRAINT fk_diary_entries_recorder FOREIGN KEY (recorded_by) REFERENCES users(id),
    CONSTRAINT fk_diary_entries_updater FOREIGN KEY (updated_by) REFERENCES users(id),
    CONSTRAINT fk_diary_entries_deleter FOREIGN KEY (deleted_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE diary_comments (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    entry_id INT UNSIGNED NOT NULL,
    body VARCHAR(500) NOT NULL,
    created_by INT UNSIGNED NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NULL,
    deleted_at DATETIME NULL,
    deleted_by INT UNSIGNED NULL,
    KEY idx_diary_comments_entry (entry_id),
    CONSTRAINT fk_diary_comments_entry FOREIGN KEY (entry_id) REFERENCES diary_entries(id),
    CONSTRAINT fk_diary_comments_creator FOREIGN KEY (created_by) REFERENCES users(id),
    CONSTRAINT fk_diary_comments_deleter FOREIGN KEY (deleted_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
