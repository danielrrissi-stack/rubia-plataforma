CREATE TABLE foods (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    source ENUM('taco','proprio') NOT NULL,
    taco_code SMALLINT UNSIGNED NULL,
    name VARCHAR(200) NOT NULL,
    name_search VARCHAR(200) NOT NULL,
    group_name VARCHAR(100) NULL,
    kcal DECIMAL(7,1) NULL,
    protein_g DECIMAL(6,1) NULL,
    carb_g DECIMAL(6,1) NULL,
    fat_g DECIMAL(6,1) NULL,
    fiber_g DECIMAL(6,1) NULL,
    active TINYINT(1) NOT NULL DEFAULT 1,
    created_by INT UNSIGNED NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NULL,
    UNIQUE KEY uq_foods_taco (taco_code),
    KEY idx_foods_search (name_search),
    CONSTRAINT fk_foods_creator FOREIGN KEY (created_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 AUTO_INCREMENT=100000;
CREATE TABLE food_measures (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    food_id INT UNSIGNED NOT NULL,
    source ENUM('pof','proprio') NOT NULL,
    name VARCHAR(100) NOT NULL,
    name_plural VARCHAR(100) NULL,
    grams DECIMAL(7,1) NOT NULL,
    active TINYINT(1) NOT NULL DEFAULT 1,
    created_by INT UNSIGNED NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    KEY idx_measures_food (food_id),
    CONSTRAINT fk_measures_food FOREIGN KEY (food_id) REFERENCES foods(id),
    CONSTRAINT fk_measures_creator FOREIGN KEY (created_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 AUTO_INCREMENT=100000;
CREATE TABLE meal_plans (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    patient_id INT UNSIGNED NOT NULL,
    mode ENUM('texto','estruturado') NOT NULL,
    title VARCHAR(150) NOT NULL,
    status ENUM('rascunho','publicado','substituido','encerrado') NOT NULL DEFAULT 'rascunho',
    body_text MEDIUMTEXT NULL,
    guidance_text MEDIUMTEXT NULL,
    structure_json JSON NULL,
    total_kcal DECIMAL(7,1) NULL,
    total_protein_g DECIMAL(6,1) NULL,
    total_carb_g DECIMAL(6,1) NULL,
    total_fat_g DECIMAL(6,1) NULL,
    total_fiber_g DECIMAL(6,1) NULL,
    revision INT UNSIGNED NOT NULL DEFAULT 1,
    source_template_id INT UNSIGNED NULL,
    source_plan_id INT UNSIGNED NULL,
    created_by INT UNSIGNED NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by INT UNSIGNED NULL,
    updated_at DATETIME NULL,
    last_audited_at DATETIME NULL,
    published_by INT UNSIGNED NULL,
    published_at DATETIME NULL,
    superseded_at DATETIME NULL,
    ended_by INT UNSIGNED NULL,
    ended_at DATETIME NULL,
    ended_reason VARCHAR(255) NULL,
    discarded_at DATETIME NULL,
    KEY idx_meal_plans_patient (patient_id, status),
    CONSTRAINT fk_meal_plans_patient FOREIGN KEY (patient_id) REFERENCES patients(id),
    CONSTRAINT fk_meal_plans_source FOREIGN KEY (source_plan_id) REFERENCES meal_plans(id),
    CONSTRAINT fk_meal_plans_creator FOREIGN KEY (created_by) REFERENCES users(id),
    CONSTRAINT fk_meal_plans_updater FOREIGN KEY (updated_by) REFERENCES users(id),
    CONSTRAINT fk_meal_plans_publisher FOREIGN KEY (published_by) REFERENCES users(id),
    CONSTRAINT fk_meal_plans_ender FOREIGN KEY (ended_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE meal_plan_templates (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    title VARCHAR(150) NOT NULL,
    mode ENUM('texto','estruturado') NOT NULL,
    body_text MEDIUMTEXT NULL,
    guidance_text MEDIUMTEXT NULL,
    structure_json JSON NULL,
    created_by INT UNSIGNED NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NULL,
    deleted_at DATETIME NULL,
    CONSTRAINT fk_meal_tpl_creator FOREIGN KEY (created_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE text_snippets (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    title VARCHAR(100) NOT NULL,
    body TEXT NOT NULL,
    created_by INT UNSIGNED NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NULL,
    deleted_at DATETIME NULL,
    CONSTRAINT fk_snippets_creator FOREIGN KEY (created_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
